function imgs(cat, slug, captions) {
  return captions.map((c, i) => ({
    type: "image",
    src: `assets/img/${cat}/${slug}/${String(i + 1).padStart(2, "0")}.webp`,
    caption: { zh: c[0], en: c[1] },
  }));
}

/* range: [start, end] 1-indexed page numbers sharing one section caption */
function secImgs(cat, slug, range) {
  const [start, end] = range;
  const out = [];
  for (let i = start; i <= end; i++) {
    out.push(`assets/img/${cat}/${slug}/${String(i).padStart(2, "0")}.webp`);
  }
  return out;
}

